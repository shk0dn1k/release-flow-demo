#!/usr/bin/env bash
# Использование: transfer.sh <баланс отправителя> <баланс получателя> <сумма>
# Выводит: <новый баланс отправителя> <новый баланс получателя>
set -euo pipefail
[[ $# -eq 3 ]] || { echo "использование: transfer.sh <отправитель> <получатель> <сумма>" >&2; exit 1; }
(( $3 > 0 )) || { echo "сумма должна быть положительной" >&2; exit 1; }
(( $1 >= $3 )) || { echo "недостаточно средств" >&2; exit 1; }
echo "$(bash "$(dirname "$0")/balance.sh" "$1" "-$3") $(bash "$(dirname "$0")/balance.sh" "$2" "$3")"
