#!/usr/bin/env bash
# Использование: interest.sh <баланс> <процент>
# Начисляет проценты на положительный баланс, округление вниз до целого.
set -euo pipefail
[[ $# -eq 2 ]] || { echo "использование: interest.sh <баланс> <процент>" >&2; exit 1; }
(( $1 > 0 )) || { echo "$1"; exit 0; }
bash "$(dirname "$0")/balance.sh" "$1" "$(( $1 * $2 / 100 ))"
